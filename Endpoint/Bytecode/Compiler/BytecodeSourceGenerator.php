declare(strict_types=1);

namespace Smithy\Client\Endpoint\Bytecode\Compiler;

use Smithy\Client\Endpoint\Bytecode\Bytecode;
use Smithy\Client\Endpoint\Bytecode\RulesFunctionInterface;

/**
 * Emit a PHP class that reconstructs compiled {@see Bytecode}.
 *
 * Codegen invokes this class at build time and commits the resulting PHP
 * source alongside the generated client. Runtime endpoint resolution then
 * pays only normal class-loading cost; it does not parse a model or compile
 * rules.
 *
 * The generated `get()` method caches the bytecode in a method-local
 * static, allowing every client using that generated class to share one
 * immutable instance for the life of the process.
 *
 * Function-table entries are emitted through each function's owning
 * registry, reported by {@see RulesFunctionInterface::getRegistryClass()}.
 * This avoids hard-coding provider registries and permits downstream
 * function extensions without changing the generic generator.
 */
final class BytecodeSourceGenerator
{
    /** License header that every generated PHP file starts with. */
    public const LICENSE_HEADER = "/*\n"
        . " * Copyright Amazon.com, Inc. or its affiliates."
        . " All Rights Reserved.\n"
        . " * SPDX-License-Identifier: Apache-2.0\n"
        . ' */';

    /**
     * Generate a process-cached bytecode class.
     *
     * @param string $namespace Namespace of the generated class, such as
     *                          `Example\Widget\Endpoint`.
     * @param string $className Short class name, such as
     *                          `WidgetEndpointBytecode`.
     * @param string $sourceModel Optional model path or URI included in
     *                            the generated provenance docblock.
     */
    public function generate(
        Bytecode $bytecode,
        string $namespace,
        string $className,
        string $sourceModel = ''
    ): string
    {
        $lines = [];
        $lines[] = '<?php';
        $lines[] = '';
        $lines[] = self::LICENSE_HEADER;
        $lines[] = '';
        $lines[] = 'declare(strict_types=1);';
        $lines[] = '';
        $lines[] = "namespace {$namespace};";
        $lines[] = '';
        $lines[] = 'use Smithy\\Client\\Endpoint\\Bytecode\\Bytecode;';
        $lines[] = '';
        $lines[] = '/**';
        $lines[] = " * Generated endpoint bytecode for {$className}.";
        $lines[] = ' *';
        $lines[] = ' * @generated Do not edit. Regenerated by the codegen';
        $lines[] = ' *     pipeline.';
        if ($sourceModel !== '') {
            $lines[] = " * @source {$sourceModel}";
        }
        $lines[] = ' */';
        $lines[] = "final class {$className}";
        $lines[] = '{';
        $lines[] = '    /**';
        $lines[] = '     * Return the process-cached compiled bytecode.';
        $lines[] = '     *';
        $lines[] = '     * Every client using this generated class shares';
        $lines[] = '     * the same immutable instance.';
        $lines[] = '     */';
        $lines[] = '    public static function get(): Bytecode';
        $lines[] = '    {';
        $lines[] = '        static $bytecode;';
        $lines[] = '';
        $lines[] = '        return $bytecode ??= new Bytecode(';
        $lines[] = '            code: '
            . $this->emitIntList($bytecode->code)
            . ',';
        $lines[] = '            constants: '
            . $this->emitConstants($bytecode->constants)
            . ',';
        $lines[] = '            functions: '
            . $this->emitFunctions($bytecode->functions)
            . ',';
        $lines[] = '            registers: '
            . $this->emitRegisters($bytecode->registers)
            . ',';
        $lines[] = '            inputRegisterMap: '
            . $this->emitStringIntMap($bytecode->inputRegisterMap)
            . ',';
        $lines[] = '            bddNodes: '
            . $this->emitIntList($bytecode->bddNodes)
            . ',';
        $lines[] = '            bddRoot: ' . $bytecode->bddRoot . ',';
        $lines[] = '            conditionOffsets: '
            . $this->emitIntList($bytecode->conditionOffsets)
            . ',';
        $lines[] = '            resultOffsets: '
            . $this->emitIntList($bytecode->resultOffsets)
            . ',';
        $lines[] = '            conditionTypes: '
            . $this->emitIntList($bytecode->conditionTypes)
            . ',';
        $lines[] = '            conditionOperands: '
            . $this->emitIntList($bytecode->conditionOperands);
        $lines[] = '        );';
        $lines[] = '    }';
        $lines[] = '}';
        $lines[] = '';

        return \implode("\n", $lines);
    }

    /**
     * @param list<int> $values
     */
    private function emitIntList(array $values): string
    {
        if ($values === []) {
            return '[]';
        }

        if (\count($values) <= 16) {
            return '[' . \implode(', ', $values) . ']';
        }

        $rendered = [];
        $chunk = [];
        foreach ($values as $value) {
            $chunk[] = $value;
            if (\count($chunk) === 16) {
                $rendered[] = '                '
                    . \implode(', ', $chunk);
                $chunk = [];
            }
        }
        if ($chunk !== []) {
            $rendered[] = '                ' . \implode(', ', $chunk);
        }

        return "[\n" . \implode(",\n", $rendered) . "\n            ]";
    }

    /**
     * @param list<mixed> $values
     */
    private function emitConstants(array $values): string
    {
        if ($values === []) {
            return '[]';
        }
        $rendered = [];
        foreach ($values as $v) {
            $rendered[] = '                ' . $this->emitScalar($v);
        }

        return "[\n" . \implode(",\n", $rendered) . "\n            ]";
    }

    /**
     * @param list<RulesFunctionInterface> $functions
     */
    private function emitFunctions(array $functions): string
    {
        if ($functions === []) {
            return '[]';
        }
        $rendered = [];
        foreach ($functions as $fn) {
            $rendered[] = '                ' . $this->emitFunctionRef($fn);
        }

        return "[\n" . \implode(",\n", $rendered) . "\n            ]";
    }

    private function emitFunctionRef(RulesFunctionInterface $fn): string
    {
        $registry = $fn->getRegistryClass();

        return \sprintf(
            '\\%s::get(%s)',
            \ltrim($registry, '\\'),
            \var_export($fn->getName(), true)
        );
    }

    /**
     * @param list<array{
     *     name:string,
     *     builtIn:?string,
     *     default:mixed,
     *     required:bool,
     *     type:string
     * }> $registers
     */
    private function emitRegisters(array $registers): string
    {
        if ($registers === []) {
            return '[]';
        }
        $rendered = [];
        foreach ($registers as $r) {
            $rendered[] = '                ['
                . "'name' => " . \var_export($r['name'], true) . ', '
                . "'builtIn' => " . \var_export($r['builtIn'], true) . ', '
                . "'default' => " . $this->emitScalar($r['default']) . ', '
                . "'required' => " . \var_export($r['required'], true) . ', '
                . "'type' => " . \var_export($r['type'], true)
                . ']';
        }

        return "[\n" . \implode(",\n", $rendered) . "\n            ]";
    }

    /**
     * @param array<string, int> $map
     */
    private function emitStringIntMap(array $map): string
    {
        if ($map === []) {
            return '[]';
        }
        $rendered = [];
        foreach ($map as $k => $v) {
            $rendered[] = '                '
                . \var_export($k, true)
                . ' => '
                . (int) $v;
        }

        return "[\n" . \implode(",\n", $rendered) . "\n            ]";
    }

    /**
     * Emit a PHP literal for a scalar or nested array.
     *
     * Scalars use `var_export()` for correctness. Arrays are recursively
     * formatted as short syntax and kept on one line when practical.
     */
    private function emitScalar(mixed $value): string
    {
        if ($value === null || \is_bool($value) || \is_int($value)) {
            return \var_export($value, true);
        }

        if (\is_float($value)) {
            return \var_export($value, true);
        }

        if (\is_string($value)) {
            return \var_export($value, true);
        }

        if (\is_array($value)) {
            return $this->emitArray($value);
        }

        throw new \RuntimeException(
            'Unsupported constant type: ' . \get_debug_type($value)
        );
    }

    /**
     * Emit short array syntax without rewriting quoted PHP source.
     *
     * List ordering and associative keys are preserved exactly because
     * both can be significant to the generated bytecode.
     *
     * @param array<mixed> $value
     */
    private function emitArray(array $value): string
    {
        if ($value === []) {
            return '[]';
        }

        $isList = \array_is_list($value);
        $parts = [];
        foreach ($value as $key => $item) {
            $encoded = $this->emitScalar($item);
            $parts[] = $isList
                ? $encoded
                : \var_export($key, true) . ' => ' . $encoded;
        }

        $singleLine = '[' . \implode(', ', $parts) . ']';
        if (\strlen($singleLine) <= 80 && !\str_contains($singleLine, "\n")) {
            return $singleLine;
        }

        $lines = [];
        foreach ($parts as $part) {
            $lines[] = '    ' . $this->indent($part);
        }

        return "[\n" . \implode(",\n", $lines) . "\n]";
    }

    private function indent(string $value): string
    {
        return \str_replace("\n", "\n    ", $value);
    }
}
