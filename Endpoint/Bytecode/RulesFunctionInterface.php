<?php

declare(strict_types=1);

namespace Smithy\Client\Endpoint\Bytecode;

/**
 * A native function callable from endpoint bytecode.
 *
 * Extension functions are registered by name in a {@see Bytecode}'s
 * function table. The evaluator dispatches to them via `FN0`..`FN`
 * opcodes. Implementations receive already-popped stack values as
 * plain PHP scalars/arrays and return a plain PHP value.
 *
 * Implementations should be stateless and fast - they run inside the
 * hot resolveEndpoint() loop.
 */
interface RulesFunctionInterface
{
    /**
     * Function name as it appears in Smithy rules (for example,
     * "substring"). Used only at compile time when the compiler
     * resolves `fn` references to function-table indices.
     */
    public function getName(): string;

    /**
     * Fully-qualified class name of the registry that owns this function.
     * The registry class **MUST** expose a static
     * `get(string $name): RulesFunctionInterface` method that returns
     * the function instance for the given name.
     *
     * Used by {@see \Smithy\Client\Endpoint\Bytecode\Compiler\BytecodeSourceGenerator}
     * to emit a static-call expression that reconstructs the function
     * from a generated bytecode file. The generic Smithy generator
     * must not hard-code provider-specific classes.
     */
    public function getRegistryClass(): string;

    /**
     * Argument count. Used by the compiler to select the appropriate
     * `FNn` opcode. Return `-1` for variadic functions (dispatched via `FN`).
     */
    public function getArgumentCount(): int;

    /**
     * Zero-argument invocation.
     */
    public function apply0(): mixed;

    /**
     * One-argument invocation.
     */
    public function apply1(mixed $a0): mixed;

    /**
     * Two-argument invocation.
     */
    public function apply2(mixed $a0, mixed $a1): mixed;

    /**
     * Three-argument invocation.
     */
    public function apply3(mixed $a0, mixed $a1, mixed $a2): mixed;

    /**
     * Variadic invocation. `$args` is guaranteed to have exactly
     * `getArgumentCount()` entries (or match the caller's supplied arity
     * for variadic functions).
     *
     * @param list<mixed> $args
     */
    public function apply(array $args): mixed;
}
