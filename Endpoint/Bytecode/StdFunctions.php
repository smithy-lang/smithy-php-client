            }

            public function apply3(mixed $a0, mixed $a1, mixed $a2): mixed
            {
                return null;
            }

            public function apply(array $args): mixed
            {
                $input = $args[0] ?? null;
                $start = $args[1] ?? 0;
                $stop = $args[2] ?? 0;
                if (!\is_string($input)
                    || !\is_int($start)
                    || !\is_int($stop)
                ) {
                    return null;
                }

                return Evaluator::substring(
                    $input,
                    $start,
                    $stop,
                    (bool) ($args[3] ?? false)
                );
            }
        };
    }

