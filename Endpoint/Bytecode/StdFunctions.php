            }

            public function apply(array $args): mixed
            {
                $n = \count($args);
                for ($i = 0; $i < $n - 1; $i++) {
                    if ($args[$i] !== null) {
                        return $args[$i];
                    }
                }
                // Last argument returned regardless of nullability, per spec.
                return $args[$n - 1] ?? null;
            }
        };
    }

