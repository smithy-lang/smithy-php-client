namespace Smithy\Client\Endpoint\Bytecode;

/**
 * Registry of Smithy endpoint rules standard-library functions.
 *
 * The registry implements `isSet`, `not`, `getAttr`, `substring`,
 * `stringEquals`, `booleanEquals`, `coalesce`, `split`, `ite`,
 * `uriEncode`, `parseURL`, and `isValidHostLabel`.
 *
 * The compiler lowers common functions to dedicated opcodes when their
 * shape permits it. Functions remain registered for compile-time lookup
 * and for expressions that require generic `FNn` dispatch.
 *
 * Generated bytecode reconstructs function-table entries through
 * {@see self::get()}, while compilers consume the complete registry from
 * {@see self::all()}. Provider registries can be merged with this map.
 */
final class StdFunctions
{
    /** @var array<string, RulesFunctionInterface>|null */
    private static ?array $cache = null;

    private function __construct() {}

    /**
     * Return one standard-library function by name.
     *
     * Generated endpoint bytecode uses this method to reconstruct only the
     * functions referenced by its function table.
     */
    public static function get(string $name): RulesFunctionInterface
    {
        $fn = self::all()[$name] ?? null;
        if ($fn === null) {
            throw new \InvalidArgumentException(
                "Unknown stdlib function: {$name}"
            );
        }

        return $fn;
    }

    /**
     * Return the cached standard-library registry keyed by function name.
     *
     * @return array<string, RulesFunctionInterface>
     */
    public static function all(): array
    {
        if (self::$cache !== null) {
            return self::$cache;
        }

        return self::$cache = [
            'booleanEquals'    => self::booleanEquals(),
            'stringEquals'     => self::stringEquals(),
            'isSet'            => self::isSet(),
            'not'              => self::not(),
            'getAttr'          => self::getAttr(),
            'substring'        => self::substring(),
            'uriEncode'        => self::uriEncode(),
            'parseURL'         => self::parseURL(),
            'isValidHostLabel' => self::isValidHostLabel(),
            'coalesce'         => self::coalesce(),
            'split'            => self::split(),
            'ite'              => self::ite()
        ];
    }

